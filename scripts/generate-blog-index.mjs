/**
 * Writes src/data/blogIndex.js: every post's title by slug, and the latest
 * market update's card, taken from src/data/blogPosts.js.
 *
 * Components on every page (breadcrumbs, the home page's market update
 * banner) only need a title or one card, and importing blogPosts.js for that
 * put all 1.5 MB of post content into the main bundle. The blog pages keep
 * importing the full posts. Runs before `vite build` and `vite dev`; the
 * output is committed so a fresh checkout works, and it only changes when
 * the posts do.
 */
import { writeFileSync, readFileSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { blogPosts, getLatestMarketUpdatePost } from '../src/data/blogPosts.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = join(__dirname, '../src/data/blogIndex.js');

const titles = {};
for (const post of blogPosts) {
  if (post?.slug && post?.title) titles[post.slug] = post.title;
}
const latest = getLatestMarketUpdatePost();
const latestCard = latest
  ? { slug: latest.slug, title: latest.title, excerpt: latest.excerpt || '', image: latest.image || '' }
  : null;

const out = [
  '// Generated by scripts/generate-blog-index.mjs from src/data/blogPosts.js.',
  '// Do not edit: change the post, then run `node scripts/generate-blog-index.mjs`',
  '// (the build and dev scripts run it too).',
  '',
  '/** Every post\'s title by slug. */',
  `export const BLOG_TITLES = ${JSON.stringify(titles, null, 2)};`,
  '',
  '/** The latest market update post, for the banner on the home page. */',
  `export const LATEST_MARKET_UPDATE = ${JSON.stringify(latestCard, null, 2)};`,
  '',
  '/** A post\'s title, or null for an unknown slug. */',
  'export function getBlogTitle(slug) {',
  '  return Object.prototype.hasOwnProperty.call(BLOG_TITLES, slug) ? BLOG_TITLES[slug] : null;',
  '}',
  '',
].join('\n');

const before = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null;
if (before === out) {
  console.log(`blog index: ${Object.keys(titles).length} posts, unchanged`);
} else {
  writeFileSync(outputPath, out);
  console.log(`blog index: ${Object.keys(titles).length} posts → src/data/blogIndex.js`);
}
